#!/usr/bin/env python3
"""
Upload a video to YouTube and attach a thumbnail.
Uses OAuth 2.0. The first run opens a browser to authorise.
"""
import base64
import os
import sys
from googleapiclient.discovery import build
from googleapiclient.http import MediaFileUpload
from google.auth.transport.requests import Request
from google.oauth2.credentials import Credentials
from google_auth_oauthlib.flow import InstalledAppFlow

SCOPES = [
    "https://www.googleapis.com/auth/youtube.upload",
    "https://www.googleapis.com/auth/youtube.readonly",
]


def get_service():
    creds = None
    token_file = "token.json"

    if os.path.exists(token_file):
        creds = Credentials.from_authorized_user_file(token_file, SCOPES)

    if not creds or not creds.valid:
        if creds and creds.expired and creds.refresh_token:
            creds.refresh(Request())
        else:
            if not os.path.exists("client_secret.json"):
                print("❌ client_secret.json not found. Download it from Google Cloud Console.")
                sys.exit(1)
            flow = InstalledAppFlow.from_client_secrets_file("client_secret.json", SCOPES)
            creds = flow.run_local_server(port=0)

        with open(token_file, "w", encoding="utf-8") as f:
            f.write(creds.to_json())

    return build("youtube", "v3", credentials=creds)


def read_file(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read().strip()


def main():
    # Read metadata generated by generate_content.py
    title = read_file("content/title.txt")
    description = read_file("content/description.txt")
    tags_line = read_file("content/tags.txt")
    tags = [t.strip() for t in tags_line.split(",") if t.strip()]

    video_path = "final_video.mp4"
    thumb_path = "thumbnail.jpg"

    if not os.path.exists(video_path):
        print(f"❌ Video not found: {video_path}")
        sys.exit(1)
    if not os.path.exists(thumb_path):
        print(f"❌ Thumbnail not found: {thumb_path}")
        sys.exit(1)

    youtube = get_service()

    # 1️⃣ Insert video
    body = {
        "snippet": {
            "title": title,
            "description": description,
            "tags": tags,
            "categoryId": "22",  # People & Blogs
            "defaultLanguage": "en",
        },
        "status": {"privacyStatus": "private"},
    }

    media = MediaFileUpload(video_path, mimetype="video/mp4", resumable=True)
    request = youtube.videos().insert(part="snippet,status", body=body, media_body=media)
    response = request.execute()
    video_id = response["id"]
    print(f"✅ Video uploaded: https://youtu.be/{video_id} (private)")

    # 2️⃣ Set thumbnail
    with open(thumb_path, "rb") as f:
        thumb_data = f.read()
    youtube.thumbnails().set(
        videoId=video_id,
        image=base64.b64encode(thumb_data).decode(),
    ).execute()
    print(f"✅ Thumbnail attached to video {video_id}")


if __name__ == "__main__":
    main()